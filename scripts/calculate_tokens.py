"""Write token counts of AGENTS.md, localized AGENTS.md, .agents/rules and .agents/skills to .agents/cost.md."""

from dataclasses import dataclass
from pathlib import Path
import re

import tiktoken

ENCODING = "o200k_base"
ALWAYS_ON_TRIGGER_RE = re.compile(r"^---\s*\n(.*?)\n---", re.DOTALL)


@dataclass(frozen=True)
class FileTokens:
    rel_path: str
    load: str
    category: str
    tokens: int


def is_always_on_rule(path: Path) -> bool:
    """Return True when a rule's YAML frontmatter sets trigger: always_on."""
    text = path.read_text(encoding="utf-8")
    match = ALWAYS_ON_TRIGGER_RE.match(text)
    if not match:
        return False
    return bool(re.search(r"^\s*trigger\s*:\s*always_on\s*$", match.group(1), re.MULTILINE))


def find_files(repo_root: Path) -> list[tuple[str, str, Path]]:
    """Return (load, category, path) tuples for all tracked agent files."""
    agents_dir = repo_root / ".agents"
    entries: list[tuple[str, str, Path]] = []

    root_agents = repo_root / "AGENTS.md"
    if root_agents.is_file():
        entries.append(("Always-On", "Core", root_agents))

    for path in sorted(repo_root.rglob("AGENTS.md")):
        if path == root_agents:
            continue
        if any(part in {".git", ".agents"} for part in path.relative_to(repo_root).parts):
            continue
        entries.append(("On-Demand", "Localized", path))

    rules_dir = agents_dir / "rules"
    if rules_dir.is_dir():
        for path in sorted(rules_dir.glob("*.md")):
            if is_always_on_rule(path):
                entries.append(("Always-On", "Rules (always_on)", path))
            else:
                entries.append(("On-Demand", "Rules", path))

    skills_dir = agents_dir / "skills"
    if skills_dir.is_dir():
        for path in sorted(skills_dir.rglob("*.md")):
            entries.append(("On-Demand", "Skills", path))

    return entries


def count_tokens(files: list[tuple[str, str, Path]], repo_root: Path) -> list[FileTokens]:
    """Count tokens per file."""
    encoder = tiktoken.get_encoding(ENCODING)
    return [
        FileTokens(
            rel_path=path.relative_to(repo_root).as_posix(),
            load=load,
            category=category,
            tokens=len(encoder.encode(path.read_text(encoding="utf-8"))),
        )
        for load, category, path in files
    ]


def render_markdown(file_tokens: list[FileTokens]) -> str:
    """Render Always-On vs On-Demand summary and per-file details as markdown."""
    always_on_total = sum(i.tokens for i in file_tokens if i.load == "Always-On")
    on_demand_total = sum(i.tokens for i in file_tokens if i.load == "On-Demand")
    grand_total = always_on_total + on_demand_total

    def cat_sum(cat: str) -> int:
        return sum(i.tokens for i in file_tokens if i.category == cat)

    summary_rows = [
        f"| **Always-On (every turn)** | **{always_on_total:,}** |",
        f"| ↳ Core (`AGENTS.md`) | {cat_sum('Core'):,} |",
    ]
    if cat_sum("Rules (always_on)"):
        summary_rows.append(f"| ↳ Rules (`always_on`) | {cat_sum('Rules (always_on)'):,} |")

    summary_rows.extend(
        [
            f"| **On-Demand** | **{on_demand_total:,}** |",
            f"| ↳ Localized (`**/AGENTS.md`) | {cat_sum('Localized'):,} |",
            f"| ↳ Rules (`model_decision`) | {cat_sum('Rules'):,} |",
            f"| ↳ Skills (`.agents/skills/`) | {cat_sum('Skills'):,} |",
            f"| **Total** | **{grand_total:,}** |",
        ]
    )

    detail_rows = [
        f"| `{item.rel_path}` | {item.load} | {item.category} | {item.tokens:,} |"
        for item in sorted(file_tokens, key=lambda item: item.tokens, reverse=True)
    ]

    return "\n".join(
        [
            "<!-- Auto-generated by scripts/calculate_tokens.py, do not edit -->",
            f"# Agent token usage ({ENCODING})",
            "",
            "| Scope | Tokens |",
            "| --- | ---: |",
            *summary_rows,
            "",
            "## Details per file",
            "",
            "| File | Load | Category | Tokens |",
            "| --- | --- | --- | ---: |",
            *detail_rows,
            "",
        ]
    )


def main() -> None:
    repo_root = Path(__file__).resolve().parent.parent
    file_tokens = count_tokens(find_files(repo_root), repo_root)
    (repo_root / ".agents" / "cost.md").write_text(render_markdown(file_tokens), encoding="utf-8")


if __name__ == "__main__":
    main()
